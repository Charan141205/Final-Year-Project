#!/usr/bin/env python3
"""Balanced-12 integrated pipeline with selectable temporal confirmation.

This is an ADD-ON. It does not overwrite balanced12_full_pipeline.py,
the trained model, manifest, feature calculator, or baseline simulator.

Modes:
  baseline-2-consecutive : uses the original Balanced12TemporalSimulator.
  gap-aware-2-of-3       : causal warm-start 2-of-3 confirmation. It can bridge
                           short gaps between consecutive window IDs only
                           within the same subject, recording, and activity.

Gap-aware links require:
  - same subject_id and recording_id,
  - same activity_label,
  - current window_id == previous window_id + 1,
  - 0 <= current.start_time_ms - previous.end_time_ms <= max gap.

It may bridge an inner feature-segment boundary. It never bridges recording
or activity boundaries or missing window IDs.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from balanced12_full_pipeline import (
    _validate_feature_table,
    raw_cappimu_to_feature_windows,
)
from balanced12_temporal_confirmation import Balanced12TemporalSimulator


HERE = Path(__file__).resolve().parent
POLICY_BASELINE = "baseline-2-consecutive"
POLICY_GAP_AWARE = "gap-aware-2-of-3"


def apply_gap_aware_2_of_3(
    frame_with_raw_predictions: pd.DataFrame,
    max_interwindow_gap_ms: float = 500.0,
) -> pd.DataFrame:
    """Apply causal gap-aware 2-of-3 warm-start confirmation.

    The input must already contain raw_predicted_binary and the metadata
    generated by the Balanced-12 inference stage. Original row order is kept.
    """
    required = [
        "subject_id", "recording_id", "window_id", "activity_label",
        "start_time_ms", "end_time_ms", "raw_predicted_binary",
    ]
    missing = [c for c in required if c not in frame_with_raw_predictions.columns]
    if missing:
        raise ValueError(f"Gap-aware policy requires columns: {missing}")
    if not (100.0 <= float(max_interwindow_gap_ms) <= 500.0):
        raise ValueError("max_interwindow_gap_ms must be between 100 and 500 ms")

    out = frame_with_raw_predictions.copy()
    n = len(out)
    if n == 0:
        raise ValueError("No windows supplied to temporal confirmation")

    # Validate the sequence fields before sorting.
    for col in ["window_id", "start_time_ms", "end_time_ms", "raw_predicted_binary"]:
        out[col] = pd.to_numeric(out[col], errors="raise")
    if not np.isfinite(out[["window_id", "start_time_ms", "end_time_ms"]].to_numpy(dtype=float)).all():
        raise ValueError("Window IDs and timestamps must be finite")
    raw = out["raw_predicted_binary"].to_numpy(dtype=np.uint8)
    if not np.isin(raw, [0, 1]).all():
        raise ValueError("raw_predicted_binary must contain only 0 and 1")

    work = out.copy()
    work["_input_position"] = np.arange(n, dtype=np.int64)
    work = work.sort_values(
        ["subject_id", "recording_id", "window_id", "_input_position"],
        kind="stable",
    ).reset_index(drop=True)

    confirmed = np.zeros(n, dtype=np.uint8)
    trigger = np.zeros(n, dtype=np.uint8)
    pending = np.zeros(n, dtype=np.uint8)
    recent_count = np.zeros(n, dtype=np.uint8)
    consecutive_count = np.zeros(n, dtype=np.int32)
    interwindow_gap = np.full(n, np.nan, dtype=np.float64)
    linked_flag = np.zeros(n, dtype=np.uint8)
    temporal_rule = f"gap_aware_2_of_3_warm_start_{int(max_interwindow_gap_ms)}ms"

    # Positions are in sorted work order. Each subject + recording is isolated.
    grouped_positions = work.groupby(["subject_id", "recording_id"], sort=False).indices
    for positions in grouped_positions.values():
        positions = np.asarray(positions, dtype=np.int64)
        history: list[int] = []
        run = 0
        previous_window_id: int | None = None
        previous_end: float | None = None
        previous_activity: str | None = None
        previous_confirmed = 0

        for pos in positions:
            row = work.iloc[pos]
            window_id = int(row["window_id"])
            start_ms = float(row["start_time_ms"])
            end_ms = float(row["end_time_ms"])
            activity = str(row["activity_label"])
            raw_value = int(row["raw_predicted_binary"])
            input_pos = int(row["_input_position"])

            gap_ms = np.nan
            linked = False
            if previous_window_id is not None and previous_end is not None:
                gap_ms = start_ms - previous_end
                linked = (
                    window_id == previous_window_id + 1
                    and activity == previous_activity
                    and 0.0 <= gap_ms <= float(max_interwindow_gap_ms)
                )

            if not linked:
                history = []
                run = 0
                previous_confirmed = 0
            else:
                linked_flag[input_pos] = 1
                interwindow_gap[input_pos] = gap_ms

            # Track the uninterrupted raw-positive run for diagnostics.
            run = run + 1 if raw_value else 0
            consecutive_count[input_pos] = run

            # Causal warm-start: first two linked observations can confirm.
            history.append(raw_value)
            history = history[-3:]
            positives_in_recent = int(sum(history))
            current_confirmed = int(len(history) >= 2 and positives_in_recent >= 2)

            recent_count[input_pos] = positives_in_recent
            confirmed[input_pos] = current_confirmed
            pending[input_pos] = int(raw_value == 1 and current_confirmed == 0)
            trigger[input_pos] = int(current_confirmed == 1 and previous_confirmed == 0)

            previous_confirmed = current_confirmed
            previous_window_id = window_id
            previous_end = end_ms
            previous_activity = activity

    out["consecutive_positive_windows"] = consecutive_count
    out["positive_windows_in_last_3"] = recent_count
    out["interwindow_gap_ms"] = interwindow_gap
    out["gap_linked_to_previous_window"] = linked_flag
    out["pending_positive"] = pending
    out["confirmed_fall"] = confirmed
    out["alert_trigger"] = trigger
    out["temporal_rule"] = temporal_rule
    out["temporal_policy"] = POLICY_GAP_AWARE
    out["max_interwindow_gap_ms"] = float(max_interwindow_gap_ms)
    return out


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Integrated Balanced-12 pipeline with selectable temporal confirmation"
    )
    parser.add_argument(
        "--mode", choices=["feature-table", "raw-cappimu"], default="feature-table",
        help="Use prepared feature windows or one raw CAPPIMU participant recording.",
    )
    parser.add_argument("--input", required=True, help="Input CSV path")
    parser.add_argument("--output-dir", required=True, help="Output directory")
    parser.add_argument("--split", choices=["train", "validation", "test"], default=None,
                        help="Optional feature-table split filter.")
    parser.add_argument("--subject-id", default=None,
                        help="Required for raw-cappimu mode, e.g. subject_8.")
    parser.add_argument(
        "--temporal-policy",
        choices=[POLICY_BASELINE, POLICY_GAP_AWARE],
        default=POLICY_BASELINE,
        help="Baseline is the unchanged two-consecutive rule; gap-aware uses 2-of-3.",
    )
    parser.add_argument(
        "--max-interwindow-gap-ms", type=float, default=500.0,
        help="Gap-aware maximum link gap, tested range 100..500 ms (default 500).",
    )
    args = parser.parse_args()

    input_path = Path(args.input)
    if not input_path.is_file():
        raise FileNotFoundError(f"Input CSV not found: {input_path}")

    if args.mode == "feature-table":
        frame = pd.read_csv(input_path)
        if args.split:
            if "split" not in frame.columns:
                raise ValueError("--split was supplied, but input has no 'split' column")
            frame = frame.loc[frame["split"] == args.split].copy()
            if frame.empty:
                raise ValueError(f"No rows found for split '{args.split}'")
    else:
        if not args.subject_id:
            raise ValueError("--subject-id is required for --mode raw-cappimu")
        if args.split:
            raise ValueError("--split applies only to --mode feature-table")
        frame = raw_cappimu_to_feature_windows(input_path, args.subject_id)
        print(f"Created {len(frame):,} non-overlapping 50-sample feature windows")

    _validate_feature_table(frame)

    # Always obtain probabilities and raw predictions from the existing,
    # unchanged Balanced-12 model and operating threshold.
    simulator = Balanced12TemporalSimulator(min_consecutive=2)
    result = simulator.predict_dataframe(frame)

    if args.temporal_policy == POLICY_BASELINE:
        result["temporal_policy"] = POLICY_BASELINE
        result["max_interwindow_gap_ms"] = np.nan
        # The baseline output is intentionally left exactly as generated by
        # the original simulator.
        selected_gap = None
    else:
        result = apply_gap_aware_2_of_3(
            result, max_interwindow_gap_ms=args.max_interwindow_gap_ms
        )
        selected_gap = float(args.max_interwindow_gap_ms)

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    predictions_path = output_dir / "balanced12_full_pipeline_predictions.csv"
    alerts_path = output_dir / "balanced12_alert_events.csv"
    summary_path = output_dir / "balanced12_full_pipeline_summary.json"

    result.to_csv(predictions_path, index=False)
    result.loc[result["alert_trigger"] == 1].to_csv(alerts_path, index=False)

    manifest_path = HERE / "trained_models" / "balanced12_decision_tree_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    summary: dict[str, Any] = {
        "pipeline": "Balanced-12 inference with selectable temporal confirmation",
        "input_mode": args.mode,
        "temporal_policy": args.temporal_policy,
        "max_interwindow_gap_ms": selected_gap,
        "windows_processed": int(len(result)),
        "raw_positive_windows": int(result["raw_predicted_binary"].sum()),
        "pending_positive_windows": int(result["pending_positive"].sum()),
        "confirmed_fall_windows": int(result["confirmed_fall"].sum()),
        "alert_trigger_events": int(result["alert_trigger"].sum()),
        "threshold": float(manifest["selected_operating_threshold"]),
        "model_feature_order": list(manifest["feature_order"]),
        "limitations": [
            "Offline CAPPIMU simulation, not live footwear sensing.",
            "Regional pressure channels are proxies, not physical footwear FSR measurements.",
            "The IMU is knee-mounted, not shoe-mounted.",
            "Labels are activity/window-level, not precise fall-onset annotations.",
            "Alerts are model outputs, not verified real-world falls.",
            "Gap-aware confirmation is experimental; the original two-consecutive policy remains the baseline.",
        ],
        "prediction_csv": str(predictions_path),
        "alert_events_csv": str(alerts_path),
    }
    summary_path.write_text(json.dumps(summary, indent=2), encoding="utf-8")

    print("\nBALANCED-12 SELECTABLE TEMPORAL PIPELINE COMPLETED")
    print("--------------------------------------------------")
    print(f"Input mode:                 {args.mode}")
    print(f"Temporal policy:            {args.temporal_policy}")
    if selected_gap is not None:
        print(f"Maximum inter-window gap:   {selected_gap:g} ms")
    print(f"Windows processed:          {len(result):,}")
    print(f"Raw positive windows:       {int(result['raw_predicted_binary'].sum()):,}")
    print(f"Pending positive windows:   {int(result['pending_positive'].sum()):,}")
    print(f"Confirmed fall windows:    {int(result['confirmed_fall'].sum()):,}")
    print(f"Alert trigger events:       {int(result['alert_trigger'].sum()):,}")
    print(f"Predictions saved to:       {predictions_path}")
    print(f"Alert events saved to:      {alerts_path}")
    print(f"Summary saved to:           {summary_path}")


if __name__ == "__main__":
    main()
